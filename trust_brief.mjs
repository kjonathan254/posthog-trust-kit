#!/usr/bin/env node
/**
 * Trust Kit: weekly trust brief data-sheet generator.
 *
 * Pulls live numbers from PostHog and prints a markdown data sheet: funnel,
 * conversion signals this week vs previous week (with deltas), guardrails,
 * coverage notes. Wrap it in interpretation - the script is the hands, the
 * analyst (human or agent) is the brain.
 *
 * Works with a READ-ONLY personal API key (every call is a read), so this
 * brick survives key downgrades.
 *
 * Usage:
 *   export POSTHOG_PERSONAL_API_KEY=phx_...
 *   node trust_brief.mjs --config config.json                # sheet to stdout
 *   node trust_brief.mjs --config config.json --out b.md --quiet  # file only
 *                                                    (CI: public Action logs
 *                                                     would otherwise leak
 *                                                     the sheet contents)
 */

const HOST = (process.env.POSTHOG_HOST || "https://us.posthog.com").replace(/\/+$/, "");
const arg = (flag, fallback) => {
  const i = process.argv.indexOf(flag);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const CONFIG_PATH = arg("--config", "config.json");

const { readFileSync } = await import("fs");
const CFG = JSON.parse(readFileSync(CONFIG_PATH, "utf8"));

if (!process.env.POSTHOG_PERSONAL_API_KEY) {
  console.error("POSTHOG_PERSONAL_API_KEY is not set");
  process.exit(1);
}
if (!CFG.project_id || CFG.project_id === "0") {
  console.error("Set config.project_id (PostHog project numeric id, from the URL /project/<id>/)");
  process.exit(1);
}

function fail(context, status, body) {
  console.error(`FAIL ${context}: HTTP ${status}`);
  try { console.error(JSON.stringify(body).slice(0, 400)); } catch { console.error(String(body).slice(0, 400)); }
  process.exit(1);
}

async function api(path, opts = {}) {
  for (let attempt = 1; attempt <= 4; attempt++) {
    const res = await fetch(`${HOST}/api/projects/${CFG.project_id}${path}`, {
      ...opts,
      headers: {
        Authorization: `Bearer ${process.env.POSTHOG_PERSONAL_API_KEY}`,
        "Content-Type": "application/json",
        ...(opts.headers || {}),
      },
      body: opts.body ? JSON.stringify(opts.body) : undefined,
    });
    if (res.ok) return res.json().catch(() => ({}));
    const json = await res.json().catch(() => ({}));
    if ([429, 502, 503, 504].includes(res.status) && attempt < 4) {
      await new Promise((r) => setTimeout(r, attempt * 4000));
      continue;
    }
    fail((opts.method || "GET") + " " + path, res.status, json);
  }
}

// one multi-series trends query; returns {event: total}
async function countsFor(date_from, date_to) {
  const all = [...CFG.signals, ...(CFG.guardrails || [])];
  const series = all.map((s) => ({ kind: "EventsNode", event: s.event }));
  const range = date_to ? { date_from, date_to } : { date_from };
  const out = await api(`/query/`, { method: "POST", body: { query: { kind: "TrendsQuery", series, dateRange: range, interval: "week" } } });
  if (out.error) fail("query", 500, { error: out.error });
  const totals = {};
  for (const s of out.results || []) {
    const ev = s.filter?.properties?.[0]?.values?.[0] || s.action?.name || s.label;
    totals[ev] = (totals[ev] || 0) + (s.count ?? s.data?.reduce((a, b) => a + b, 0) ?? 0);
  }
  return totals;
}

async function funnel30d() {
  const out = await api(`/query/`, {
    method: "POST",
    body: {
      query: {
        kind: "FunnelsQuery",
        series: CFG.funnel.map((f) => ({ kind: "EventsNode", event: f.event, name: f.label })),
        dateRange: { date_from: "-30d" },
        interval: "week",
        funnelsFilter: {
          funnelWindowInterval: CFG.funnel_window_days || 14,
          funnelWindowIntervalUnit: "day",
          funnelOrderType: "ordered",
        },
      },
    },
  });
  if (out.error) fail("funnel", 500, { error: out.error });
  return (out.results || []).map((s) => ({ name: s.name, count: s.count }));
}

function fmtDelta(a, b) {
  if (a === 0 && b === 0) return "-";
  if (b === 0) return `new (+${a})`;
  const pct = Math.round(((a - b) / b) * 100);
  return `${pct >= 0 ? "+" : ""}${pct}%`;
}

async function main() {
  const today = new Date().toISOString().slice(0, 10);
  const [weekA, weekB, funnel] = await Promise.all([
    countsFor("-7d"),
    countsFor("-14d", "-7d"),
    funnel30d(),
  ]);
  const since = await countsFor(CFG.launch_date); // one call, reused by every row

  const L = [];
  L.push(`# Trust Brief - data sheet (${today})`);
  L.push("");
  L.push(`_Generated by posthog-trust-kit \`trust_brief.mjs\` from live PostHog data (project ${CFG.project_id}). Read-only safe._`);
  L.push("");
  L.push(`## 1. Funnel (30-day window, ${CFG.funnel_window_days || 14}-day conversion limit)`);
  L.push("");
  L.push(funnel.length ? funnel.map((s, i) => `${i + 1}. ${s.name}: **${s.count}**`).join("\n") : "_no funnel rows returned_");
  L.push("");
  L.push(`## 2. Conversion signals (week vs previous week)`);
  L.push("");
  L.push(`| Signal | Last 7 days | Prior 7 days | Change | Since launch (${CFG.launch_date}) |`);
  L.push(`|---|---|---|---|---|`);
  for (const s of CFG.signals) {
    const a = weekA[s.event] || 0, b = weekB[s.event] || 0;
    L.push(`| ${s.label} | ${a} | ${b} | ${fmtDelta(a, b)} | ${since[s.event] || 0} |`);
  }
  if (CFG.guardrails?.length) {
    L.push("");
    L.push(`## 3. Guardrails (week vs previous week)`);
    L.push("");
    L.push(`| Guardrail | Last 7 days | Prior 7 days | Since launch |`);
    L.push(`|---|---|---|---|`);
    for (const g of CFG.guardrails) {
      const a = weekA[g.event] || 0, b = weekB[g.event] || 0;
      L.push(`| ${g.label} | ${a} | ${b} | ${since[g.event] || 0} |`);
    }
  }
  L.push("");
  L.push(`## Notes`);
  L.push("");
  L.push(`- Judge the funnel on week-over-week deltas, not totals.`);
  L.push(`- Event names in the config are the contract with your instrumentation - rename both sides together.`);
  L.push("");

  const sheet = L.join("\n");
  if (!process.argv.includes("--quiet")) console.log(sheet);

  const outIdx = process.argv.indexOf("--out");
  if (outIdx > -1 && process.argv[outIdx + 1]) {
    const { writeFileSync } = await import("fs");
    writeFileSync(process.argv[outIdx + 1], sheet + "\n");
    console.error(`\nwritten -> ${process.argv[outIdx + 1]}`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
